package main

import (
	"flag"
	"fmt"
	"sort"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/encoding/protowire"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"
)

const (
	serviceAuthRequiredField protowire.Number = 50010
	methodAuthRequiredField  protowire.Number = 50011
)

type procedureRule struct {
	Procedure string
	Required  bool
}

func main() {
	var flags flag.FlagSet
	protogen.Options{ParamFunc: flags.Set}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedEditionsMinimum = descriptorpb.Edition_EDITION_PROTO3
		gen.SupportedEditionsMaximum = descriptorpb.Edition_EDITION_MAX
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL | pluginpb.CodeGeneratorResponse_FEATURE_SUPPORTS_EDITIONS)

		for _, f := range gen.Files {
			if !f.Generate {
				continue
			}
			rules := collectRulesForFile(f)

			fileName := uniqueOutFileName(f.Desc.Path())
			g := gen.NewGeneratedFile(fileName, "github.com/otpki/otpki-protobuf/gen/otpki/auth/authmeta")
			g.P("// Code generated by protoc-gen-authrequired. DO NOT EDIT.")
			g.P("package authmeta")
			if len(rules) != 0 {
				g.P()
				g.P("import \"github.com/otpki/otpki-protobuf/authmap\"")
			}
			g.P()
			g.P("func init() {")
			sort.Slice(rules, func(i, j int) bool {
				return rules[i].Procedure < rules[j].Procedure
			})
			for _, r := range rules {
				g.P(fmt.Sprintf("\tauthmap.AuthRequiredByProcedure[%q] = %t", r.Procedure, r.Required))
			}
			g.P("}")
		}
		return nil
	})
}

func collectRulesForFile(f *protogen.File) []procedureRule {
	if len(f.Services) == 0 {
		return nil
	}

	seen := map[string]bool{}
	var out []procedureRule

	pkg := string(f.Desc.Package())
	for _, svc := range f.Services {
		serviceRequired, serviceSet := getBoolExtensionFromUnknown(svc.Desc.Options(), serviceAuthRequiredField)
		serviceDefault := true
		if serviceSet {
			serviceDefault = serviceRequired
		}

		for _, m := range svc.Methods {
			methodRequired, methodSet := getBoolExtensionFromUnknown(m.Desc.Options(), methodAuthRequiredField)
			required := serviceDefault
			if methodSet {
				required = methodRequired
			}

			procedure := "/" + pkg + "." + string(svc.Desc.Name()) + "/" + string(m.Desc.Name())
			if seen[procedure] {
				continue
			}
			seen[procedure] = true
			if !required {
				out = append(out, procedureRule{Procedure: procedure, Required: required})
			}
		}
	}

	return out
}

func uniqueOutFileName(protoPath string) string {
	s := protoPath
	s = strings.TrimPrefix(s, "./")
	s = strings.TrimSuffix(s, ".proto")
	s = strings.ReplaceAll(s, "/", "_")
	s = strings.ReplaceAll(s, "\\", "_")
	s = strings.ReplaceAll(s, ".", "_")
	return fmt.Sprintf("gen/otpki/auth/authmeta/auth_required_%s.gen.go", s)
}

func getBoolExtensionFromUnknown(opts any, fieldNumber protowire.Number) (bool, bool) {
	if opts == nil {
		return false, false
	}

	m, ok := opts.(interface{ ProtoReflect() protoreflect.Message })
	if !ok {
		return false, false
	}

	unknown := m.ProtoReflect().GetUnknown()
	var (
		val bool
		set bool
	)

	for len(unknown) > 0 {
		num, typ, n := protowire.ConsumeTag(unknown)
		if n < 0 {
			break
		}
		unknown = unknown[n:]

		switch typ {
		case protowire.VarintType:
			v, n := protowire.ConsumeVarint(unknown)
			if n < 0 {
				return val, set
			}
			if num == fieldNumber {
				val = v != 0
				set = true
			}
			unknown = unknown[n:]
		case protowire.Fixed32Type:
			_, n := protowire.ConsumeFixed32(unknown)
			if n < 0 {
				return val, set
			}
			unknown = unknown[n:]
		case protowire.Fixed64Type:
			_, n := protowire.ConsumeFixed64(unknown)
			if n < 0 {
				return val, set
			}
			unknown = unknown[n:]
		case protowire.BytesType:
			_, n := protowire.ConsumeBytes(unknown)
			if n < 0 {
				return val, set
			}
			unknown = unknown[n:]
		default:
			return val, set
		}
	}

	return val, set
}
