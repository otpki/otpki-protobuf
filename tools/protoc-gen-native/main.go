package main

// CURRENT LIMITATIONS:
// - does not handle oneofs
// - does not handle pointers to slices, nor should it (e.g. *[]string)
// - does not handle map types

import (
	"flag"
	"fmt"
	"os"
	"strings"
	"text/template"

	"github.com/samber/oops"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/types/descriptorpb"
	"google.golang.org/protobuf/types/pluginpb"

	options "protoc-gen-native/api"
)

type ConverterInfo struct {
	NeedsConverter    bool
	ConverterToProto  string
	ConverterToNative string
}

type FieldInfo struct {
	Name          string
	Type          string
	ConverterInfo ConverterInfo
}
type MessageInfo struct {
	StructName string
	Fields     []FieldInfo
}

var structTmpl = template.Must(template.New("").Parse(`
// {{.StructName}}Native is the native typing representation of {{.StructName}}
type {{.StructName}}Native struct {
	{{- range .Fields}}
	{{.Name}} {{.Type}}
	{{- end }}
}
	
// ToProto converts a {{.StructName}}Native to a {{.StructName}}
func (n *{{.StructName}}Native) ToProto() (*{{.StructName}}, error) {
	if n == nil {
		return nil, nil
	}
	var err error
	protoStruct := &{{.StructName}}{}
	{{- range .Fields}}
	{{- if .ConverterInfo.NeedsConverter}}
	protoStruct.{{.Name}}, err = {{.ConverterInfo.ConverterToProto}}
	if err != nil {
		return nil, fmt.Errorf("error converting {{.Name}}: %w", err)
	}
	{{- else}}
	protoStruct.{{.Name}} = n.{{.Name}}
	{{- end}}
	{{- end}}
	return protoStruct, nil
}

// FromProto converts a {{.StructName}} to a {{.StructName}}Native
func (p *{{.StructName}}) ToNative() (*{{.StructName}}Native, error) {
	if p == nil {
		return nil, nil
	}
	var err error
	nativeStruct := &{{.StructName}}Native{}
	{{- range .Fields}}
	{{- if .ConverterInfo.NeedsConverter}}
	nativeStruct.{{.Name}}, err = {{.ConverterInfo.ConverterToNative}}
	if err != nil {
		return nil, fmt.Errorf("error converting {{.Name}}Native: %w", err)
	}
	{{- else}}
	nativeStruct.{{.Name}} = p.{{.Name}}
	{{- end}}
	{{- end}}
	return nativeStruct, nil
}
`))

func main() {
	var flags flag.FlagSet
	converterPkgFlag := flags.String("converters_pkg", "", "Path to the converters pkg")
	protogen.Options{
		ParamFunc: flags.Set,
	}.Run(func(gen *protogen.Plugin) error {
		gen.SupportedEditionsMinimum = descriptorpb.Edition_EDITION_PROTO3
		gen.SupportedEditionsMaximum = descriptorpb.Edition_EDITION_MAX
		gen.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL | pluginpb.CodeGeneratorResponse_FEATURE_SUPPORTS_EDITIONS)

		// get the package path from flags
		converterPackagePath = *converterPkgFlag
		if converterPackagePath == "" {
			gen.Error(oops.Errorf("missing required parameter 'converters_pkg'"))
			return nil
		}

		// set the converter package path for parsing
		if err := setConverterPackage(converterPackagePath); err != nil {
			gen.Error(oops.Errorf("failed to load converters package: %v", err))
			return nil
		}

		// generate files
		for _, f := range gen.Files {
			if !f.Generate {
				continue
			}
			generateFile(gen, f)
		}
		return nil
	})
}

// generateFile generates a native struct for each message in the given file
func generateFile(gen *protogen.Plugin, file *protogen.File) *protogen.GeneratedFile {
	// only parse if it has the generate_native option
	if !fileHasGenerateNative(file) {
		return nil
	}

	filename := file.GeneratedFilenamePrefix + ".native.pb.go"
	g := gen.NewGeneratedFile(filename, file.GoImportPath)

	g.P("// Code generated by protoc-gen-native-go. DO NOT EDIT.")
	g.P()
	g.P("package ", file.GoPackageName)
	g.P()

	// import format for errors
	g.QualifiedGoIdent(protogen.GoIdent{GoImportPath: "fmt"})

	// use a map to act as hash set
	neededConverters := map[string]bool{}

	// process all messages in this proto file
	for _, message := range file.Messages {
		if !message.Desc.IsMapEntry() && messageHasGenerateNative(message) {
			// generate the struct and converter methods
			converters, err := generateNativeStructAndReceivers(g, message)
			if err != nil {
				gen.Error(err)
				return nil
			}

			// add converters to our set
			for _, converter := range converters {
				neededConverters[converter] = true
			}
		}
	}

	// import converter functions that are actually needed
	// use file.GoPackageName as the package identifier for the registry
	importConverterFunctions(g, neededConverters, string(file.GoPackageName))

	return g
}

// generateNativeStructAndReceivers generates the native struct and receiver methods for a given message
// returns a list of converter function names needed by this message
func generateNativeStructAndReceivers(g *protogen.GeneratedFile, message *protogen.Message) ([]string, error) {
	msgInfo := MessageInfo{
		StructName: message.GoIdent.GoName,
	}

	// track converter functions needed by this message
	var neededConverters []string

	// for each field in the given message
	for _, field := range message.Fields {
		// validate
		if err := validateFieldOptions(field); err != nil {
			return nil, err
		}

		// get converter info
		convInfo, toProtoFuncName, toNativeFuncName := getFieldConverterInfo(g, field)
		if convInfo.NeedsConverter {
			neededConverters = append(neededConverters, toProtoFuncName)
			neededConverters = append(neededConverters, toNativeFuncName)
		}

		// append each field to the template
		msgInfo.Fields = append(msgInfo.Fields, FieldInfo{
			Name:          field.GoName,
			Type:          getQualifiedGoTypeString(g, field),
			ConverterInfo: convInfo,
		})
	}

	// write "Native" struct to the generated file (including converter functions)
	err := structTmpl.Execute(g, msgInfo)
	if err != nil {
		return nil, err
	}

	return neededConverters, nil
}

// importConverterFunctions writes all converter functions to the generated file
// using the GlobalRegistry to prevent duplicate function declarations across files in the same package
func importConverterFunctions(g *protogen.GeneratedFile, neededConverters map[string]bool, packageName string) {
	if len(neededConverters) == 0 {
		return
	}

	// needed converters, including package dependencies
	allNeededFunctions := map[string]bool{}

	// for each converter, find its dependency
	for funcName := range neededConverters {
		// copy converter
		allNeededFunctions[funcName] = true

		// recursively find dependencies
		deps := getFunctionDependencies(funcName)
		for depName := range deps {
			allNeededFunctions[depName] = true
		}
	}

	// track imported packages to avoid duplicates
	importedPackages := map[string]bool{}

	g.P("// Converter functions for native types")
	g.P()

	// import and write each needed function
	for funcName := range allNeededFunctions {
		// check if this function has already been registered for this package
		// if it has, skip generating it to avoid duplicate declarations
		if GlobalRegistry.IsFunctionRegistered(packageName, funcName) {
			continue
		}

		// get imports needed by this function
		imports := getFunctionImports(funcName)
		for _, imp := range imports {
			// skip if we've already imported this package
			if importedPackages[imp] {
				continue
			}
			// import the package
			g.QualifiedGoIdent(protogen.GoIdent{
				GoImportPath: protogen.GoImportPath(imp),
			})
			importedPackages[imp] = true
		}

		// write the function definition
		funcContent := getFunctionString(g, funcName)
		if funcContent != "" {
			g.P("// " + strings.Replace(funcName, "Convert", "convert", 1) + " comes from the converter package")
			g.P(funcContent)
			g.P()

			// register this function as generated for this package
			GlobalRegistry.RegisterFunction(packageName, funcName)
		}
	}
}

// getFieldOptions pulls the metadata from a particular field
func getFieldOptions(field *protogen.Field) (goNativeType string, goNativeImportPath string) {
	if field.Desc.Options().ProtoReflect().Has(options.E_GoNativeType.TypeDescriptor()) {
		goNativeType = proto.GetExtension(field.Desc.Options(), options.E_GoNativeType).(string)
	}
	if field.Desc.Options().ProtoReflect().Has(options.E_GoNativeImportPath.TypeDescriptor()) {
		goNativeImportPath = proto.GetExtension(field.Desc.Options(), options.E_GoNativeImportPath).(string)
	}
	return
}

// validateFieldOptions ensures that the given proto field is suitable for
// "native" struct validation
func validateFieldOptions(field *protogen.Field) error {
	goNativeType, goNativeImportPath := getFieldOptions(field)
	// if neither are specified, we are good
	if goNativeType == "" && goNativeImportPath == "" {
		return nil
	}

	// if only one is specified, but not the other, error
	if goNativeType == "" {
		return oops.Errorf("field %s.%s has no go_native_type", field.Parent.Desc.Name(), field.Desc.Name())
	}
	if goNativeImportPath == "" {
		return oops.Errorf("field %s.%s has no go_native_import_path", field.Parent.Desc.Name(), field.Desc.Name())
	}

	// "optional" creates a synthetic oneof we want to avoid
	if field.Oneof != nil && !field.Oneof.Desc.IsSynthetic() {
		// explicitly do not handle explicit oneofs for native types
		return oops.Errorf("cannot use oneof when generating native %s.%s", field.Parent.Desc.Name(), field.Desc.Name())
	}

	return nil
}

// messageHasGenerateNative checks to see if the message has been tagged to
// allow "native" generation for this struct
func messageHasGenerateNative(msg *protogen.Message) bool {
	if msg.Desc.Options() == nil {
		return false
	}
	ext := proto.GetExtension(msg.Desc.Options(), options.E_GenerateNative)
	generate, ok := ext.(bool)
	return ok && generate
}

// fileHasGenerateNative checks to see if the current file
// is worth spitting out a proto file for
func fileHasGenerateNative(file *protogen.File) bool {
	for _, message := range file.Messages {
		if messageHasGenerateNative(message) {
			return true
		}
	}
	return false
}

// extractBaseTypeName extracts the base type name from a potentially qualified type name
// removes slice and pointer notation, as well as package prefixes. Does not support a pointer to a slice
func extractBaseTypeName(typeName string) (baseTypeName string, isSlice, isPointer bool) {
	if strings.HasPrefix(typeName, "[]") {
		isSlice = true
		typeName = strings.TrimPrefix(typeName, "[]")
	}

	if strings.HasPrefix(typeName, "*") {
		isPointer = true
		typeName = strings.TrimPrefix(typeName, "*")
	}
	baseTypeName = getUnqualifiedBaseTypeName(typeName)
	return
}

// getUnqualifiedBaseTypeName extracts the base type name without package prefix
// for example: "crypto/x509.ExtKeyUsage" -> "ExtKeyUsage"
func getUnqualifiedBaseTypeName(typeName string) string {
	parts := strings.Split(typeName, ".")
	if len(parts) > 1 {
		return parts[len(parts)-1]
	}
	return typeName
}

// getQualifiedGoTypeString returns the qualified go type string for a field, as well as imports it
// the qualified go type string is the full type name, including package prefix (e.g. "x509.ExtKeyUsage")
func getQualifiedGoTypeString(g *protogen.GeneratedFile, field *protogen.Field) string {
	goNativeType, goNativeImportPath := getFieldOptions(field)

	// if this field did not have native type specified,
	// use the default go type parsing
	if goNativeType == "" || goNativeImportPath == "" {
		return getGoTypeForField(g, field)
	}

	baseTypeName, isSlice, isPointer := extractBaseTypeName(goNativeType)

	// get the "imported" name, as well as import the required module
	// into the generated file
	qualifiedBaseType := g.QualifiedGoIdent(protogen.GoIdent{
		GoName:       baseTypeName,
		GoImportPath: protogen.GoImportPath(goNativeImportPath),
	})

	// re-add the pointer and/or slice notation
	if isPointer {
		qualifiedBaseType = "*" + qualifiedBaseType
	}
	if isSlice {
		qualifiedBaseType = "[]" + qualifiedBaseType
	}
	return qualifiedBaseType
}

// getFieldConverterInfo generates links converter methods to a particular field
func getFieldConverterInfo(g *protogen.GeneratedFile, field *protogen.Field) (fieldInfo ConverterInfo, toProtoFuncName, toNativeFuncName string) {
	goNativeType, goNativeImportPath := getFieldOptions(field)

	// if this field did not have native type specified,
	// we can just return it as is
	if goNativeType == "" || goNativeImportPath == "" {
		return
	}

	// get the names of the converter functions from the base type
	toProtoFuncName, toNativeFuncName = getConverterFunctionName(extractBaseTypeName(goNativeType))

	// check to see if these functions exist
	toProtoExists := functionExists(toProtoFuncName)
	toNativeExists := functionExists(toNativeFuncName)

	// use these functions if they exist
	if toProtoExists && toNativeExists {
		fieldInfo.NeedsConverter = true
		fieldInfo.ConverterToProto = fmt.Sprintf("%s(n.%s)", strings.Replace(toProtoFuncName, "Convert", "convert", 1), field.GoName)
		fieldInfo.ConverterToNative = fmt.Sprintf("%s(p.%s)", strings.Replace(toNativeFuncName, "Convert", "convert", 1), field.GoName)

	} else {
		// if not, add a warning but continue
		protoType := getGoTypeForField(g, field)
		if !toProtoExists {
			_, _ = fmt.Fprintln(os.Stderr, fmt.Sprintf("WARNING: Missing converter function: %s(%s) (%s, error)\n\tProto type: %-21s-> Native type: %s",
				toProtoFuncName, goNativeType, protoType, protoType, goNativeType))
			toProtoFuncName = ""
		}
		if !toNativeExists {
			_, _ = fmt.Fprintln(os.Stderr, fmt.Sprintf("WARNING: Missing converter function: %s(%s) (%s, error)\n\tNative type: %-20s-> Proto type: %s",
				toNativeFuncName, protoType, goNativeType, goNativeType, protoType))
			toNativeFuncName = ""
		}
	}
	return
}

// getConverterFunctionName returns the names of the converter functions for a given base type
// it does not support pointer to slice types (ex. *[]int)
func getConverterFunctionName(baseTypeName string, isSlice bool, isPointer bool) (toProtoFuncName string, toNativeFuncName string) {
	toProtoFuncName += "Convert" + baseTypeName
	toNativeFuncName += "ConvertProtoTo" + baseTypeName

	if isPointer {
		toProtoFuncName += "Pointer"
		toNativeFuncName += "Pointer"
	}
	if isSlice {
		toProtoFuncName += "Slice"
		toNativeFuncName += "Slice"
	}
	toProtoFuncName += "ToProto"
	return
}
